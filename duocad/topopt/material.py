"""許容応力・ヤング率・印刷低減係数の唯一の定義。"""

from __future__ import annotations

# 許容応力。**40 という数字だけをハードコードしない**(出所を問われる)。

# PETG の降伏応力。フィラメントのデータシート級の公称値。実際に使う銘柄の値へ差し替えられる。
PETG_YIELD_MPA = 50.0

# 3Dプリントを想定した低減係数。**留保**: 積層方向(Z)には楽観的 —— FDM の層間接着は
# ふつう XY 方向の40〜60%で、0.8 には届かない。さらにトポロジー最適化が出す形は、どの部分が
# どの向きに荷重を受けるかが最適化の時点では分からないので、造形姿勢が決まるまで一つの
# スカラーでは異方性を代表できない。**暫定値である。**
PRINT_DERATE = 0.8

# 許容応力 = 降伏応力 × 低減係数。**安全率(利用者入力)とは二重に効く**(意図どおり。
# 材料側の低減と設計側の余裕を片方に畳み込むと、造形法を変えたときにどちらを動かすか分からなくなる)。
DEFAULT_ALLOWABLE_MPA = PETG_YIELD_MPA * PRINT_DERATE  # 40.0

# 表示用の変位を出すためだけの名目値(PETG のヤング率はおよそ1.5〜2.1GPa)。安全率は E に依存しない
# (`stress.UnitScale`)ので結果には影響しない。
DEFAULT_YOUNGS_MODULUS_MPA = 2000.0

# ポアソン比。`fem` の既定値で、製品は既定のまま `Model` を作る。E と違い応力場の形に効く。
POISSON_RATIO = 0.3
